import { FACULTY } from "@/lib/syllabus-api";
import { isSameProgram } from "@/lib/programs";

/**
 * その学生がその開講クラスを履修登録できるか。design.md §6.1。
 *
 * **履修可否の正本はシラバスの対象課程である。** 履修要項側(`curricula/`)は
 * 履修可否を持たない。判定に使うのは api-clean の `GET /syllabi/{code}` が返す
 * `programs`(対象課程)と `faculties`(対象学部)で、規則は下の `canRegister()` の
 * 3分岐だけである。
 *
 * ## なぜ履修要項側では判定できないのか
 *
 * 2つの取り違えが起きていた。どちらも「履修要項の科目」と「シラバスの開講クラス」が
 * 1対多であることに由来する。
 *
 * 1. **クラス指定の教養教育科目。** 「仏教の思想A」は11クラス開講され、課程ごとに
 *    履修できるクラスが決まっている(火1の3クラスは電子情報通信+機械工学・ロボ、
 *    火2の2クラスは知能情報メディア、水1の3クラスは応用化学+環境生態工学、
 *    水2の2クラスは数理・情報科学、木5の1クラスは課程指定なしの後期開講=救済措置)。
 *    履修要項側の対応表(`offerings/`)は科目名 → コードの対応しか持たず課程を
 *    区別しないため、11クラス全部に `必修` が付いていた
 * 2. **他課程の専攻科目。** マージ済み履修要項には他課程の科目が
 *    `own: false` で入る。`own` を履修可否の代理指標として使っていたが、
 *    これは両方向に外していた(下記)
 *
 * ## `own` が代理指標として不正確な理由
 *
 * 履修要項の「専門関連科目」は**学修プログラムを構成する科目のうち他課程が主体と
 * なって開講する科目**である(履修要項 s04)。他課程の全科目ではない。実データで
 * 突き合わせると、学修プログラム含有科目は例外なく全課程に開かれており、
 * 非含有の科目は主開講課程にしか開かれていない。
 *
 * | | コード数 | |
 * |---|---|---|
 * | 学修プログラム含有科目 | 242 | 100% が全6課程対象 |
 * | 非含有の専攻科目 | 400 | 97%(389)が主開講課程のみ |
 *
 * つまり `own: false` の中に、実際は履修できる科目が埋もれていた(2026年度開講・
 * 2024年度入学の知能情報メディア課程で224コード。PR2 で `専門関連` タグを付ける対象)。
 * 逆に `own: true` の教養教育科目には履修できないクラスが混ざっており、検索結果に
 * 現れる 430 コードのうち 126 コードが誤ったタグだった。
 *
 * ## 学修プログラムのデータは持たない
 *
 * 対象課程が学修プログラム含有を代理しているため不要である(上表。逆向きも、
 * 履修できる他課程科目のほぼ全数が含有科目)。加えて、学修プログラムの
 * 表(履修要項 s05【8】。PNG画像)に載らないのに複数課程へ開かれている
 * `Y009` 系の共通科目(情報と職業・職業指導・地学概論・生物学概論・地学実験・
 * 生物学実験の11コード)は**対象課程でしか判別できない**ため、画像を転記すると
 * かえって取りこぼす。
 */

/** 履修可否の判定に使うシラバス側の値。`SyllabusDetail` の部分型。 */
export type CourseTarget = {
  /** 対象課程。空のことがある(全学向けの教養教育科目・学部名義のクラス) */
  programs: string[];
  /** 対象学部。`programs` が空のときの拠りどころになる */
  faculties: string[];
};

/**
 * 学生の課程がその開講クラスを履修できるか。
 *
 * - 対象課程に学生の課程が入っている → 履修可
 * - 対象課程が空で、対象学部に先端理工学部が入る → 課程指定なし。履修可
 * - それ以外 → 他課程指定のクラス。履修不可
 *
 * 課程名の比較は `isSameProgram()` に委ねる。コード `06` は入学年度で改称され
 * (環境生態工学課程 → 環境科学課程)、api-clean は両方の名前を別々に持つため、
 * 文字列の一致では取り違える(§4.4.2)。
 *
 * @param programName 学生プロファイルの課程名(`StudentProfile.program`)
 */
export function canRegister(
  target: CourseTarget,
  programName: string | null | undefined,
): boolean {
  if (!programName) return false;
  if (target.programs.length === 0) return target.faculties.includes(FACULTY);
  return target.programs.some((name) => isSameProgram(name, programName));
}
