/**
 * 展示用のダミー学生プロファイル(design.md §11)。**実在の成績ではない。**
 *
 * 6課程に1件ずつ置き、学年は1〜3回生に2件ずつ割り振る。いずれも**2026年9月作成の
 * 成績表**(2026年度前期まで成績確定)を読み込んだ状態を想定する。
 *
 * | 課程 | 学年 | 入学年度 |
 * |---|---|---|
 * | 01 数理・情報科学課程 | 2回生 | 2025 |
 * | 02 知能情報メディア課程 | 3回生 | 2024 |
 * | 03 電子情報通信課程 | 1回生 | 2026 |
 * | 04 機械工学・ロボティクス課程 | 1回生 | 2026 |
 * | 05 応用化学課程 | 2回生 | 2025 |
 * | 06 環境生態工学課程(現・環境科学課程) | 3回生 | 2024 |
 *
 * 作り方は次のとおり。実物の成績表に寄せるため、履修要項データから外れた科目を
 * 入れない:
 *
 * - 科目名・単位・区分は各入学年度の `curricula/admission-<年度>/`(課程ファイルと
 *   00-liberal-arts.yaml)の設置科目から採る。表記も転記元どおりとする(2026年度
 *   入学の教養教育科目は全角英字「英語総合1（Ａ）」など)。突き合わせは NFKC で
 *   正規化するため(`lib/courseTitle.ts`)、成績表の全角表記とも一致する
 * - 年度・学期は配当年次と開講学期から決める。クォーター科目も成績表には
 *   「前期 / 後期」で刷られるため、`term` は前期・後期のどちらかにする
 * - 2026年度前期の科目は `offerings/2026/` で開講が確認できるものに限る
 * - 1学期の登録単位数は履修登録制限(1・2年次22単位、3年次24単位)に収める
 * - 成績は点数(60点以上で合格)。不合格は知能情報メディア課程(2科目)と
 *   機械工学・ロボティクス課程(1科目)だけに置き、他の4件は全科目合格とする。
 *   **再履修して合格した科目は1件だけ**で、年度・学期は合格した学期になる
 *   (成績表は科目ごとに1列で、評価欄は最終結果。`lib/pdf/parseGradeReport.ts`)
 * - 成績発表前の科目は `***`(登録科目)として `registered` で載せる
 *
 * 知能情報メディア課程は履修提案のスモーク(`backend/scripts/smoke_proposal.py`)と
 * 同じ科目構成であり、点数だけを補った。
 *
 * `issuedOn` / `enrollment` は持たせない。手入力・デモでは次に登録する学期を
 * 今日の日付から決めるためである(`lib/targetTerm.ts`)。
 */

type Row = [
  title: string,
  year: number,
  term: Course["term"],
  credits: number,
  rawScore: string,
];

/** 1行1科目の表から `Course` を作る。状態は成績表の評価と同じ規則で決める */
function courses(rows: Row[]): Course[] {
  return rows.map(([title, year, term, credits, rawScore]) => ({
    title,
    year,
    term,
    credits,
    status: statusOf(rawScore),
    rawScore,
  }));
}

function statusOf(rawScore: string): Course["status"] {
  if (rawScore === "***" || rawScore === "*") return "registered";
  if (rawScore === "J" || rawScore === "K") return "withdrawn";
  return parseInt(rawScore, 10) >= 60 ? "passed" : "failed";
}

